export function getTranslation(lang: LanguageCode | string): UiTranslations {
  if (lang === 'auto') return UI_STRINGS.en;
  return UI_STRINGS[lang] || UI_STRINGS.en;
}

export function getLanguageInfo(code: LanguageCode | string): LanguageInfo {
  return (
    SUPPORTED_LANGUAGES.find((l) => l.code === code) ||
    SUPPORTED_LANGUAGES[0]
  );
}
