export function getScenario(id: string): Scenario {
  return SCENARIOS.find((s) => s.id === id) || SCENARIOS[0];
}

export function getScenarioTranscript(
  scenario: Scenario,
  lang: string
): { id: string; speaker: 'caller' | 'user'; text: string; timestampSeconds: number }[] {
  if (scenario.transcripts[lang]) {
    return scenario.transcripts[lang];
  }
  if (scenario.transcripts.en) {
    return scenario.transcripts.en;
  }
  return scenario.transcripts.hi || [];
}

